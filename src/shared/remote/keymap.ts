/** Scancode de uma tecla física, ou null se ela não existe no protocolo. */
export function scancodeFor(code: string): number | null {
  return Object.prototype.hasOwnProperty.call(KEYMAP, code) ? KEYMAP[code] : null;
}

export function isExtended(scancode: number): boolean {
  return (scancode & E) !== 0;
}
